import type { Plugin, ResolvedConfig } from 'vite'
import matter from 'gray-matter'
// oxlint-disable-next-line import/no-nodejs-modules
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
// oxlint-disable-next-line import/no-nodejs-modules
import path from 'node:path'

export interface LocalizedString {
	en: string
	nl: string
}

export interface PostFrontmatter {
	title: LocalizedString
	date: string
	updated: string
	excerpt: LocalizedString
	author: string
	coverImage: string
	categories: string[]
	tags: string[]
	draft: boolean
}

export type BlogPost = PostFrontmatter & {
	slug: string
	page: string
}

// oxlint-disable-next-line max-statements
const generateBlogPostsFile = async (config: ResolvedConfig) => {
		const blogDirectory = path.resolve(config.root, 'src/routes/(web)/[[locale]]/blog'),
			entries = await readdir(blogDirectory, { withFileTypes: true }),
			outputFile = path.resolve(config.root, 'src/lib/data/blogposts.ts'),
			posts: BlogPost[] = []

		for (const entry of entries) {
			if (!entry.isDirectory()) {
				continue
			}
			let rawContent: string
			try {
				rawContent = await readFile(path.join(blogDirectory, entry.name, '+page.svx'), 'utf8')
			} catch {
				try {
					rawContent = await readFile(path.join(blogDirectory, entry.name, '+page.md'), 'utf8')
				} catch {
					continue
				}
			}

			const { data } = matter(rawContent) as unknown as { data: PostFrontmatter }
			if (data.draft) {
				continue
			}
			const slug = entry.name.replaceAll('\\', '/')
			posts.push({
				page: `/blog/${slug}`,
				slug,
				...data
			})
		}

		posts.sort((a, b) => parseDate(b.date) - parseDate(a.date))

		const contents = `// This file is generated by vite-plugin-blog-metadata. Do not edit manually.\nexport const posts = ${JSON.stringify(posts)} as const`

		await mkdir(path.dirname(outputFile), { recursive: true })
		await writeFile(outputFile, contents)
	},
	parseDate = (dateString: string) => {
		const [day, month, year] = dateString.split('/', 3)

		return new Date(Number(year), Number(month) - 1, Number(day)).getTime()
	}

export const blogMetadata = (): Plugin => {
	let config: ResolvedConfig

	return {
		async buildStart() {
			await generateBlogPostsFile(config)
		},

		configResolved(resolvedConfig) {
			config = resolvedConfig
		},

		async handleHotUpdate({ file, server }) {
			const blogDirectory = path.resolve(config.root, 'src/routes/(web)/blog')

			if (!file.startsWith(blogDirectory)) {
				return
			}

			if (!file.endsWith('+page.md') && !file.endsWith('+page.svx')) {
				return
			}

			await generateBlogPostsFile(config)

			const module = server.moduleGraph.getModuleById(
				path.resolve(config.root, 'src/lib/data/blogposts.ts')
			)

			if (module) {
				server.moduleGraph.invalidateModule(module)
			}
		},

		name: 'vite-plugin-blog-metadata'
	}
}
